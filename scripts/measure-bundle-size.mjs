#!/usr/bin/env node
/**
 * measure-bundle-size.mjs — closes #16
 *
 * Walks the dashboard's `.next/static` output after a production build
 * and reports:
 *   - Total static asset size (chunks + CSS + media + workers)
 *   - Size of the 10 largest JS chunks
 *   - Per-route chunk attribution via `.next/app-build-manifest.json`
 *
 * Why this script exists:
 *   PR #8 introduced Recharts v3 (12 chart primitives), Lottie (sign-in
 *   animation), and 200+ city records (smart-address). Issue #16 asks
 *   for a concrete bundle-size number so we can track regressions
 *   going forward. The Next 16 build output doesn't print First Load
 *   JS by default with Turbopack, so we have to compute it from the
 *   manifest ourselves.
 *
 * Usage:
 *   pnpm --filter dashboard build         # populate .next/
 *   node scripts/measure-bundle-size.mjs  # from workspace root
 *
 * Output:
 *   - stdout: ASCII table of largest chunks + per-route totals
 *   - docs/BUNDLE-SIZE-LATEST.md: overwritten each run, committed for
 *     drift detection
 */

import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs"
import { join } from "node:path"

const ROOT = process.cwd()
const NEXT_DIR = join(ROOT, "apps/dashboard/.next")
const STATIC_DIR = join(NEXT_DIR, "static")

if (!existsSync(NEXT_DIR)) {
  console.error(`❌ ${NEXT_DIR} not found. Run \`pnpm --filter dashboard build\` first.`)
  process.exit(1)
}

function walk(dir, accept = () => true) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...walk(full, accept))
    } else if (entry.isFile() && accept(full)) {
      out.push({ path: full, size: statSync(full).size })
    }
  }
  return out
}

function human(bytes) {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`
}

// ── 1. Tally everything under .next/static ────────────────────────────────
// `.next/` can exist without `.next/static/` (partial build, build failure
// where Turbopack bailed before emitting assets). Guard explicitly so we
// surface a clear message instead of a raw ENOENT stack from `readdirSync`.
if (!existsSync(STATIC_DIR)) {
  console.error(`❌ ${STATIC_DIR} not found. The build may have failed or produced an unexpected output structure. Re-run \`pnpm --filter dashboard build\` and check for errors.`)
  process.exit(1)
}
const allStatic = walk(STATIC_DIR)
const byCategory = { js: 0, css: 0, media: 0, other: 0 }
for (const f of allStatic) {
  if (f.path.endsWith(".js")) byCategory.js += f.size
  else if (f.path.endsWith(".css")) byCategory.css += f.size
  else if (/\.(woff2?|ttf|otf|png|jpg|jpeg|gif|svg|webp|avif)$/.test(f.path)) byCategory.media += f.size
  else byCategory.other += f.size
}
const totalStatic = byCategory.js + byCategory.css + byCategory.media + byCategory.other

// ── 2. Largest JS chunks ──────────────────────────────────────────────────
const jsChunks = allStatic
  .filter((f) => f.path.endsWith(".js"))
  .sort((a, b) => b.size - a.size)
  .slice(0, 15)

// ── 3. Per-route attribution ──────────────────────────────────────────────
// Next 16 + Turbopack does NOT emit `app-build-manifest.json` with the
// chunk attribution that older Webpack builds produced — the per-route
// section is therefore "unavailable" in this build mode. Track this in
// the doc so we don't pretend we have a number we don't.
let routeAttribution = []
const manifestPath = join(NEXT_DIR, "app-build-manifest.json")
if (existsSync(manifestPath)) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"))
  const pages = manifest.pages ?? {}
  for (const [route, files] of Object.entries(pages)) {
    if (!Array.isArray(files)) continue
    let total = 0
    for (const f of files) {
      const p = join(NEXT_DIR, f.replace(/^\//, ""))
      if (existsSync(p)) total += statSync(p).size
    }
    routeAttribution.push({ route, bytes: total, fileCount: files.length })
  }
  routeAttribution.sort((a, b) => b.bytes - a.bytes)
}

function relPath(absolute) {
  // Normalize to POSIX separators relative to the workspace root,
  // even on Windows where ROOT contains backslashes.
  const normRoot = ROOT.replace(/\\/g, "/")
  const normP = absolute.replace(/\\/g, "/")
  return normP.startsWith(normRoot + "/")
    ? normP.slice(normRoot.length + 1)
    : normP
}

// ── 4. Render output ──────────────────────────────────────────────────────
const lines = []
const stamp = new Date().toISOString().slice(0, 10)
lines.push(`# Dashboard bundle size — ${stamp}`)
lines.push("")
lines.push("> Generated by `node scripts/measure-bundle-size.mjs`. Closes #16.")
lines.push("> Commit this file after every run that lands a significant change so we can diff over time.")
lines.push("")
lines.push("## Totals (`apps/dashboard/.next/static`)")
lines.push("")
lines.push("| Category | Size |")
lines.push("|---|---|")
lines.push(`| JavaScript chunks | ${human(byCategory.js)} |`)
lines.push(`| CSS | ${human(byCategory.css)} |`)
lines.push(`| Media (fonts, images) | ${human(byCategory.media)} |`)
lines.push(`| Other | ${human(byCategory.other)} |`)
lines.push(`| **Total static** | **${human(totalStatic)}** |`)
lines.push("")
lines.push("## Largest JS chunks")
lines.push("")
lines.push("| Rank | File | Size |")
lines.push("|---:|---|---:|")
jsChunks.forEach((c, i) => {
  lines.push(`| ${i + 1} | \`${relPath(c.path)}\` | ${human(c.size)} |`)
})
lines.push("")
if (routeAttribution.length === 0) {
  lines.push("## Per-route bundle (First Load JS)")
  lines.push("")
  lines.push("⚠️ Next 16 with Turbopack does not emit per-route chunk attribution in the build manifests (no `app-build-manifest.json`). Track totals + largest-chunks above; per-route numbers require either reverting to Webpack mode or running `pnpm dlx @next/bundle-analyzer` against the build.")
  lines.push("")
}
if (routeAttribution.length > 0) {
  lines.push("## Per-route bundle (First Load JS estimate)")
  lines.push("")
  lines.push("First Load JS per route = sum of every JS chunk the route lists in `app-build-manifest.json`. Includes shared runtime, so absolute numbers are higher than the per-route DELTA — but the relative ordering is reliable.")
  lines.push("")
  lines.push("| Route | First Load JS | Chunks |")
  lines.push("|---|---:|---:|")
  for (const r of routeAttribution) {
    lines.push(`| \`${r.route}\` | ${human(r.bytes)} | ${r.fileCount} |`)
  }
  lines.push("")
}
lines.push("## Budget reference")
lines.push("")
lines.push("Per #16:")
lines.push("- Any route exceeding **250 KB First Load JS** → dynamic-import Recharts at the chart level (`next/dynamic`, `ssr: false`).")
lines.push("- `/sign-in` exceeding **150 KB First Load JS** → lazy-load the Lottie JSON.")
lines.push("")
lines.push("## How to re-run")
lines.push("")
lines.push("```bash")
lines.push("pnpm --filter dashboard build")
lines.push("node scripts/measure-bundle-size.mjs")
lines.push("```")

const docPath = join(ROOT, "docs/BUNDLE-SIZE-LATEST.md")
writeFileSync(docPath, lines.join("\n") + "\n")

// ── 5. Stdout summary ────────────────────────────────────────────────────
console.log(`\n╔══════════════════════════════════════════════════╗`)
console.log(`║  Dashboard bundle size — ${stamp}              ║`)
console.log(`╚══════════════════════════════════════════════════╝\n`)
console.log(`Total static:     ${human(totalStatic)}`)
console.log(`  JavaScript:     ${human(byCategory.js)}`)
console.log(`  CSS:            ${human(byCategory.css)}`)
console.log(`  Media:          ${human(byCategory.media)}`)
console.log(`  Other:          ${human(byCategory.other)}`)
console.log(`\nTop 5 chunks:`)
jsChunks.slice(0, 5).forEach((c, i) => {
  console.log(`  ${i + 1}. ${human(c.size).padEnd(10)} ${relPath(c.path)}`)
})
if (routeAttribution.length > 0) {
  console.log(`\nHeaviest routes (First Load JS):`)
  routeAttribution.slice(0, 8).forEach((r) => {
    const flag = r.bytes > 250 * 1024 ? " ⚠️ over 250KB budget" : ""
    console.log(`  ${human(r.bytes).padEnd(10)} ${r.route}${flag}`)
  })
}
console.log(`\n✅ Wrote ${docPath}\n`)

// ── Budget enforcement ────────────────────────────────────────────────────
// Read the budget file (apps/dashboard/.bundle-budget.json) and fail the
// run if any tracked metric exceeds its limit. Without this, the workflow
// uploaded an artifact but enforced nothing — same "Phase 2 deferred"
// pattern the review feedback called out.
const BUDGET_PATH = join(ROOT, "apps/dashboard/.bundle-budget.json")
if (existsSync(BUDGET_PATH)) {
  const budget = JSON.parse(readFileSync(BUDGET_PATH, "utf8"))
  const limits = budget.baseline ?? {}
  const violations = []
  const totalJs = byCategory.js
  const largestChunk = jsChunks[0]?.size ?? 0

  if (limits.totalStaticBytes && totalStatic > limits.totalStaticBytes) {
    violations.push(
      `Total static: ${human(totalStatic)} exceeds budget ${human(limits.totalStaticBytes)}`,
    )
  }
  if (limits.jsBytes && totalJs > limits.jsBytes) {
    violations.push(
      `JS bytes: ${human(totalJs)} exceeds budget ${human(limits.jsBytes)}`,
    )
  }
  if (limits.largestChunkBytes && largestChunk > limits.largestChunkBytes) {
    violations.push(
      `Largest chunk: ${human(largestChunk)} exceeds budget ${human(limits.largestChunkBytes)}`,
    )
  }

  if (violations.length > 0) {
    console.error("❌ Bundle-size budget exceeded:")
    for (const v of violations) console.error(`   - ${v}`)
    console.error(
      "\nRaise the limit in apps/dashboard/.bundle-budget.json deliberately, with a same-PR justification.",
    )
    process.exit(1)
  }
  console.log(
    `✅ Bundle within budget (total ${human(totalStatic)} / ${human(limits.totalStaticBytes)}, JS ${human(totalJs)} / ${human(limits.jsBytes)}, top chunk ${human(largestChunk)} / ${human(limits.largestChunkBytes)})\n`,
  )
} else {
  console.warn(`⚠️ No budget file at ${BUDGET_PATH} — bundle-size gate is inactive.\n`)
}
